    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String proveedor = jComboBox1.getSelectedItem().toString();
String guia = jTextField1.getText();
String declarada = jTextField2.getText();
String contada = jTextField3.getText();
String estado = jComboBox2.getSelectedItem().toString();
String observaciones = jTextField4.getText();

String sql = "INSERT INTO cajas "
        + "(id_proveedor, fecha_recepcion, numero_guia, "
        + "cantidad_declarada, cantidad_contada, estado, observaciones) "
        + "VALUES (?, NOW(), ?, ?, ?, ?, ?)";

try {
    Connection cn = CONEXION.conectar();
    PreparedStatement ps = cn.prepareStatement(sql);

    ps.setInt(1, Integer.parseInt(
            proveedor.replace("Proveedor ", "")));

    ps.setString(2, guia);
    ps.setInt(3, Integer.parseInt(declarada));
    ps.setInt(4, Integer.parseInt(contada));
    ps.setString(5, estado);
    ps.setString(6, observaciones);

    ps.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Caja registrada correctamente");

    cn.close();

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error al registrar la caja: " + e.getMessage());

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Verifique el proveedor y las cantidades ingresadas");
}
    }//GEN-LAST:event_jButton1ActionPerformed

