    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    String codigo = jTextField1.getText().trim();
String nombre = jTextField2.getText().trim();
String categoria = jComboBox1.getSelectedItem().toString();
String material = jTextField3.getText().trim();
String peso = jTextField4.getText().trim();
String calidad = jTextField5.getText().trim();
String costo = jTextField6.getText().trim();
String venta = jTextField7.getText().trim();
String ruta = jTextField8.getText().trim();

if (codigo.isEmpty() || nombre.isEmpty() || material.isEmpty()
        || peso.isEmpty() || calidad.isEmpty()
        || costo.isEmpty() || venta.isEmpty() || ruta.isEmpty()) {

    JOptionPane.showMessageDialog(this,
            "Complete todos los campos y seleccione una fotografía");

} else {

    try {

        File foto = new File(ruta);

        if (!foto.exists()) {

            JOptionPane.showMessageDialog(this,
                    "La fotografía no existe");

        } else {

            byte[] imagen = java.nio.file.Files.readAllBytes(foto.toPath());

            String sql = "INSERT INTO productos "
                    + "(codigo, nombre, id_categoria, material, peso, calidad, "
                    + "precio_costo, precio_venta, ruta_foto, imagen) "
                    + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

            try (Connection cn = CONEXION.conectar();
                 PreparedStatement ps = cn.prepareStatement(
                         sql, PreparedStatement.RETURN_GENERATED_KEYS)) {

                int idCategoria = Integer.parseInt(
                        categoria.replace("Categoria ", "").trim());

                ps.setString(1, codigo);
                ps.setString(2, nombre);
                ps.setInt(3, idCategoria);
                ps.setString(4, material);
                ps.setDouble(5, Double.parseDouble(peso));
                ps.setString(6, calidad);
                ps.setDouble(7, Double.parseDouble(costo));
                ps.setDouble(8, Double.parseDouble(venta));
                ps.setString(9, ruta);
                ps.setBytes(10, imagen);

                ps.executeUpdate();

                try (ResultSet rs = ps.getGeneratedKeys()) {

                    if (rs.next()) {

                        int id = rs.getInt(1);

                        DefaultTableModel modelo =
                                (DefaultTableModel) jTable1.getModel();

                        if (modelo.getRowCount() == 1
                                && modelo.getValueAt(0, 0) == null) {
                            modelo.setRowCount(0);
                        }

                        modelo.addRow(new Object[]{
                            id,
                            codigo,
                            nombre,
                            categoria,
                            venta,
                            "Activo"
                        });
                    }
                }

                JOptionPane.showMessageDialog(this,
                        "Producto y fotografía registrados correctamente");
            }
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error al guardar: " + e.getMessage());
    }
}
    }//GEN-LAST:event_jButton1ActionPerformed

