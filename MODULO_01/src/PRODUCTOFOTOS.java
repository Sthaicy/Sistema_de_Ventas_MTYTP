    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String producto = jComboBox1.getSelectedItem().toString();
String ruta = jTextField1.getText();

if (jComboBox1.getSelectedIndex() == 0) {

    JOptionPane.showMessageDialog(this,
            "Seleccione un producto");

} else if (ruta.isEmpty()) {

    JOptionPane.showMessageDialog(this,
            "Primero debe seleccionar una fotografía");

} else {

    String sql = "INSERT INTO producto_fotos "
            + "(id_producto, ruta_foto) "
            + "VALUES (?, ?)";

    try {

        Connection cn = CONEXION.conectar();

        PreparedStatement ps = cn.prepareStatement(sql);

        int idProducto = Integer.parseInt(
                producto.replace("Producto ", ""));

        ps.setInt(1, idProducto);
        ps.setString(2, ruta);

        ps.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Fotografía registrada correctamente");

        cn.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al guardar: " + e.getMessage());

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Seleccione un producto válido");
    }
}
    }//GEN-LAST:event_jButton2ActionPerformed

