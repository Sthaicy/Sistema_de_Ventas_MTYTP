    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        // TODO add your handling code here:
        String producto = jComboBox1.getSelectedItem().toString();
String ruta = jTextField1.getText().trim();

if (jComboBox1.getSelectedIndex() == 0) {

    JOptionPane.showMessageDialog(this,
            "Seleccione un producto");

} else if (ruta.isEmpty()) {

    JOptionPane.showMessageDialog(this,
            "Seleccione la nueva fotografía con el botón BUSCAR");

} else {

    String sql = "UPDATE producto_fotos SET ruta_foto = ? "
            + "WHERE id_producto = ?";

    try {

        Connection cn = CONEXION.conectar();
        PreparedStatement ps = cn.prepareStatement(sql);

        int idProducto = Integer.parseInt(
                producto.replace("Producto ", "").trim());

        ps.setString(1, ruta);
        ps.setInt(2, idProducto);

        int resultado = ps.executeUpdate();

        if (resultado > 0) {

            JOptionPane.showMessageDialog(this,
                    "Fotografía modificada correctamente");

        } else {

            JOptionPane.showMessageDialog(this,
                    "No existe una fotografía registrada para ese producto");
        }

        ps.close();
        cn.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al modificar: " + e.getMessage());

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "El producto seleccionado no tiene un ID válido");
    }
}
    }//GEN-LAST:event_jButton5ActionPerformed

    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        // TODO add your handling code here:
        String producto = jComboBox1.getSelectedItem().toString();

if (jComboBox1.getSelectedIndex() == 0) {

    JOptionPane.showMessageDialog(this,
            "Seleccione un producto para eliminar su fotografía");

} else {

    int confirmar = JOptionPane.showConfirmDialog(this,
            "¿Está seguro de eliminar la fotografía de este producto?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION);

    if (confirmar == JOptionPane.YES_OPTION) {

        try {

            int idProducto = Integer.parseInt(
                    producto.replace("Producto ", "").trim());

            String sql = "DELETE FROM producto_fotos WHERE id_producto = ?";

            Connection cn = CONEXION.conectar();
            PreparedStatement ps = cn.prepareStatement(sql);

            ps.setInt(1, idProducto);

            int resultado = ps.executeUpdate();

            if (resultado > 0) {

                JOptionPane.showMessageDialog(this,
                        "Fotografía eliminada correctamente");

                jTextField1.setText("");
                jLabel4.setIcon(null);
                jLabel4.setText("");

            } else {

                JOptionPane.showMessageDialog(this,
                        "No se encontró una fotografía para ese producto");
            }

            ps.close();
            cn.close();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Error al eliminar: " + e.getMessage());

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "El producto seleccionado no tiene un ID válido");
        }
    }
}
    }//GEN-LAST:event_jButton6ActionPerformed

