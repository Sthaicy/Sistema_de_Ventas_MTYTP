    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String producto = jComboBox1.getSelectedItem().toString();
String tipoMovimiento = jComboBox2.getSelectedItem().toString();
String cantidad = jTextField1.getText();
String motivo = jTextField2.getText();
String usuario = jComboBox3.getSelectedItem().toString();

String caja = "";

if (jComboBox4.getSelectedIndex() > 0) {
    caja = jComboBox4.getSelectedItem().toString();
}

if (jComboBox1.getSelectedIndex() == 0) {

    JOptionPane.showMessageDialog(this,
            "Seleccione un producto");

} else if (jComboBox2.getSelectedIndex() == 0) {

    JOptionPane.showMessageDialog(this,
            "Seleccione el tipo de movimiento");

} else if (cantidad.isEmpty()) {

    JOptionPane.showMessageDialog(this,
            "Ingrese la cantidad");

} else if (jComboBox3.getSelectedIndex() == 0) {

    JOptionPane.showMessageDialog(this,
            "Seleccione un usuario");

} else {

    String sql = "INSERT INTO movimientos_stock "
            + "(id_producto, tipo_movimiento, cantidad, motivo, id_usuario, id_caja) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    try {

        int idProducto = Integer.parseInt(
                producto.replace("Producto ", ""));

        int cantidadMovimiento = Integer.parseInt(cantidad);

        int idUsuario = Integer.parseInt(
                usuario.replace("Usuario ", ""));

        if (cantidadMovimiento <= 0) {

            JOptionPane.showMessageDialog(this,
                    "La cantidad debe ser mayor que cero");

        } else {

            Connection cn = CONEXION.conectar();

            PreparedStatement ps = cn.prepareStatement(sql);

            ps.setInt(1, idProducto);
            ps.setString(2, tipoMovimiento);
            ps.setInt(3, cantidadMovimiento);
            ps.setString(4, motivo);
            ps.setInt(5, idUsuario);

            if (caja.isEmpty()) {

                ps.setNull(6, Types.INTEGER);

            } else {

                int idCaja = Integer.parseInt(
                        caja.replace("Caja ", ""));

                ps.setInt(6, idCaja);
            }

            ps.executeUpdate();

            JOptionPane.showMessageDialog(this,
                    "Movimiento de stock registrado correctamente");

            ps.close();
            cn.close();
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al registrar el movimiento: " + e.getMessage());

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Verifique la cantidad y los datos seleccionados");
    }
}
    }//GEN-LAST:event_jButton1ActionPerformed

