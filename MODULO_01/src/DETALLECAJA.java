    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String caja = jComboBox1.getSelectedItem().toString();
String producto = jComboBox2.getSelectedItem().toString();
String declarada = jTextField1.getText();
String contada = jTextField2.getText();
String discrepancia = jComboBox3.getSelectedItem().toString();
String observacion = jTextField3.getText();

String sql = "INSERT INTO detalle_caja "
        + "(id_caja, id_producto, cantidad_declarada, "
        + "cantidad_contada, tipo_discrepancia, observacion) "
        + "VALUES (?, ?, ?, ?, ?, ?)";

try {
    Connection cn = CONEXION.conectar();
    PreparedStatement ps = cn.prepareStatement(sql);

    ps.setInt(1, Integer.parseInt(
            caja.replace("Caja ", "")));

    ps.setInt(2, Integer.parseInt(
            producto.replace("Producto ", "")));

    ps.setInt(3, Integer.parseInt(declarada));
    ps.setInt(4, Integer.parseInt(contada));
    ps.setString(5, discrepancia);
    ps.setString(6, observacion);

    ps.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Detalle de caja registrado correctamente");

    cn.close();

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error al registrar: " + e.getMessage());

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Verifique la caja, el producto y las cantidades");
}
    }//GEN-LAST:event_jButton1ActionPerformed

