    private void aniadirButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_aniadirButtonActionPerformed
        // TODO add your handling code here:
        int filaSel = jTable1.getSelectedRow();
        if (filaSel == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se ha seleccionado ningún producto.");
            return;
        }
        int idProductoReal = idsProductosCatalogo.get(filaSel);
        String nombreProd = String.valueOf(jTable1.getValueAt(filaSel, 0));
        double precioProd = Double.parseDouble(String.valueOf(jTable1.getValueAt(filaSel, 1)));
        int cantDisponible = Integer.parseInt(String.valueOf(jTable1.getValueAt(filaSel, 2)));
        String dispo = String.valueOf(jTable1.getValueAt(filaSel, 3));

        if (cantDisponible <= 0 || !dispo.equals("Disponible")) {
            javax.swing.JOptionPane.showMessageDialog(this, "No hay stock disponible.");
            return;
        }
        int idClientePrueba = 1; // ID de cliente fijo para pruebas (puedes enlazarlo a tu sesión activa)
        try {
            String sqlBuscarCarrito = "SELECT id_carrito FROM carritos WHERE id_cliente = ? AND estado = 'ACTIVO' LIMIT 1";
            int idCarrito = -1;
            try (PreparedStatement pst = conn.prepareStatement(sqlBuscarCarrito)) {
                pst.setInt(1, idClientePrueba);
                ResultSet rs = pst.executeQuery();
                if (rs.next()) {
                    idCarrito = rs.getInt("id_carrito");
                }
            }
            if (idCarrito == -1) {
                String sqlCrearCarrito = "INSERT INTO carritos (id_cliente, estado) VALUES (?, 'ACTIVO')";
                try (PreparedStatement pst = conn.prepareStatement(sqlCrearCarrito, java.sql.Statement.RETURN_GENERATED_KEYS)) {
                    pst.setInt(1, idClientePrueba);
                    pst.executeUpdate();
                    ResultSet rsKeys = pst.getGeneratedKeys();
                    if (rsKeys.next()) {
                        idCarrito = rsKeys.getInt(1);
                    }
                }
            }
            String sqlBuscarDetalle = "SELECT id_detalle_carrito, cantidad FROM detalle_carrito WHERE id_carrito = ? AND id_producto = ?";
            int idDetalle = -1;
            try (PreparedStatement pst = conn.prepareStatement(sqlBuscarDetalle)) {
                pst.setInt(1, idCarrito);
                pst.setInt(2, idProductoReal);
                ResultSet rs = pst.executeQuery();
                if (rs.next()) {
                    idDetalle = rs.getInt("id_detalle_carrito");
                }
            }
            if (idDetalle != -1) {
                String sqlUpdateDetalle = "UPDATE detalle_carrito SET cantidad = cantidad + 1 WHERE id_detalle_carrito = ?";
                try (PreparedStatement pst = conn.prepareStatement(sqlUpdateDetalle)) {
                    pst.setInt(1, idDetalle);
                    pst.executeUpdate();
                }
            } else {
                String sqlInsertDetalle = "INSERT INTO detalle_carrito (id_carrito, id_producto, cantidad, precio_unitario) VALUES (?, ?, 1, ?)";
                try (PreparedStatement pst = conn.prepareStatement(sqlInsertDetalle)) {
                    pst.setInt(1, idCarrito);
                    pst.setInt(2, idProductoReal);
                    pst.setDouble(3, precioProd);
                    pst.executeUpdate();
                }
            }
            javax.swing.JOptionPane.showMessageDialog(this, "¡Producto añadido al carrito exitosamente!");
            actualizarTabla();
        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Error al procesar el carrito: " + e.getMessage());
        }
        ventanaCarrito.actualizarCarrito();
    }//GEN-LAST:event_aniadirButtonActionPerformed

