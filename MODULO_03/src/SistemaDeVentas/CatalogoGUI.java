    public void actualizarTabla(){
        if (idsProductosCatalogo == null) {
            idsProductosCatalogo = new java.util.ArrayList<>();
        }
        idsProductosCatalogo.clear();
        
        String[] titulos = {"Nombre Prod.","Precio(Bs)","Cantidad","Disponibilidad"};
        catalogo = new DefaultTableModel(null, titulos);
        Object[] fila = new Object[4];
        String SQL = "SELECT id_producto, nombre_prod, precio, cantidad, disponibilidad FROM vw_catalogo_productos";
        try {
            PreparedStatement st = conn.prepareStatement(SQL);
            ResultSet rs = st.executeQuery();
            while(rs.next()){
                idsProductosCatalogo.add(rs.getInt("id_producto"));
                fila[0] = rs.getString("nombre_prod");
                fila[1] = rs.getDouble("precio");
                fila[2] = rs.getInt("cantidad");
                fila[3] = rs.getString("disponibilidad");
                catalogo.addRow(fila);
            }
            jTable1.setModel(catalogo);
        } catch (Exception e){
            e.printStackTrace();
        }
    }
