    public void actualizarHistorial(int idCliente) {
        String[] titulos = {"Nro. Pedido", "Fecha", "Total (Bs.)", "Estado", "Modalidad"};
        javax.swing.table.DefaultTableModel modeloHistorial = new javax.swing.table.DefaultTableModel(null, titulos){
            @Override
            public boolean isCellEditable(int fila, int col){
                return false;
            }
        };
        String sql = "SELECT p.id_pedido, p.fecha, p.total, p.estado, m.nombre AS modalidad " +
                     "FROM pedidos p " +
                     "JOIN modalidades_entrega m ON p.id_modalidad_entrega = m.id_modalidad_entrega " +
                     "WHERE p.id_cliente = ? " +
                     "ORDER BY p.fecha DESC";
        try (Connection conn = MyConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql)) { 
            pst.setInt(1, idCliente);
            ResultSet rs = pst.executeQuery();
            Object[] fila = new Object[5];
            while (rs.next()) {
                fila[0] = rs.getInt("id_pedido");
                fila[1] = rs.getTimestamp("fecha");
                fila[2] = rs.getDouble("total");
                fila[3] = rs.getString("estado");
                fila[4] = rs.getString("modalidad");
                modeloHistorial.addRow(fila);
            }
            jTable1.setModel(modeloHistorial);    
        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar el historial: " + e.getMessage());
        }
    }
    
    private void mostrarDetallePedido(int idPedido) {
        String[] titulos = {"Producto", "Cantidad", "Precio Unitario (Bs.)", "Subtotal (Bs.)"};
        javax.swing.table.DefaultTableModel modeloDetalle = new javax.swing.table.DefaultTableModel(null, titulos);
        String sql = "SELECT p.nombre, dp.cantidad, dp.precio_unitario, dp.subtotal " +
                     "FROM detalle_pedidos dp " +
                     "JOIN productos p ON dp.id_producto = p.id_producto " +
                     "WHERE dp.id_pedido = ?";
        try (Connection conn = MyConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql)) { 
            pst.setInt(1, idPedido);
            ResultSet rs = pst.executeQuery();
            Object[] fila = new Object[4];
            while (rs.next()) {
                fila[0] = rs.getString("nombre");
                fila[1] = rs.getInt("cantidad");
                fila[2] = rs.getDouble("precio_unitario");
                fila[3] = rs.getDouble("subtotal");
                modeloDetalle.addRow(fila);
            }    
            javax.swing.JTable tablaDetalle = new javax.swing.JTable(modeloDetalle);
            javax.swing.JScrollPane scrollPane = new javax.swing.JScrollPane(tablaDetalle);
            scrollPane.setPreferredSize(new java.awt.Dimension(500, 200));
            javax.swing.JOptionPane.showMessageDialog(this, scrollPane, 
                    "Detalle de Productos - Pedido Nro: " + idPedido, 
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar el detalle del pedido: " + e.getMessage());
        }
    }

