    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if (!validarFormulario()) {
        return; //n
        }
        
        try {
            Cupon cupon = obtenerCuponFormulario();
            CuponDAO dao = new CuponDAO();
            int idCupon = dao.insertar(cupon);

            if (idCupon != -1) {
                JOptionPane.showMessageDialog(this, "Cupón registrado correctamente.");
                cargarCupones(); //n
                limpiarFormulario(); //n
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo registrar el cupón.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Revise los datos ingresados.");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        if (txtIdCupon.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un cupón.");
            return;
        }

        if (!validarFormulario()) {
            return;
        }

        try {
            Cupon cupon = obtenerCuponFormulario();
            boolean actualizado = cuponDAO.actualizar(cupon);

            if (actualizado) {
                JOptionPane.showMessageDialog(this, "Cupón modificado correctamente.");
                cargarCupones();
                limpiarFormulario();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo modificar el cupón.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al modificar el cupón.");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarActionPerformed
        // TODO add your handling code here:
        if (txtIdCupon.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un cupón.");
            return;
        }

        int idCupon = Integer.parseInt(txtIdCupon.getText().trim());

        int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea desactivar este cupón?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION
        );

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        if (cuponDAO.desactivar(idCupon)) {
            JOptionPane.showMessageDialog(this, "Cupón desactivado correctamente.");
            cargarCupones();
            limpiarFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo desactivar el cupón.");
        }
    }//GEN-LAST:event_btnDesactivarActionPerformed

