    private void cargarCupones() {
        DefaultTableModel modelo = (DefaultTableModel) tblCupones.getModel();
        modelo.setRowCount(0);

        ArrayList<Cupon> lista = cuponDAO.listar();

        for (Cupon cupon : lista) {
            Object[] fila = {
                cupon.getIdCupon(),
                cupon.getIdPromocion(),
                cupon.getCodigo(),
                cupon.getLimiteGlobal(),
                cupon.getLimitePorCliente(),
                cupon.getUsosActuales(),
                cupon.getMontoMinimo(),
                cupon.getFechaInicio(),
                cupon.getFechaFin(),
                cupon.isActivo() ? "Sí" : "No"
            };
            modelo.addRow(fila);
        }
    }
    
    private void cargarCuponSeleccionado() {
        int fila = tblCupones.getSelectedRow();

        if (fila == -1) {
            return;
        }

        int idCupon = Integer.parseInt(tblCupones.getValueAt(fila, 0).toString());
        Cupon cupon = cuponDAO.buscarPorId(idCupon);

        if (cupon == null) {
            return;
        }

        txtIdCupon.setText(String.valueOf(cupon.getIdCupon()));
        txtIdPromocion.setText(String.valueOf(cupon.getIdPromocion()));
        txtCodigo.setText(cupon.getCodigo());
        txtLimiteGlobal.setText(String.valueOf(cupon.getLimiteGlobal()));
        txtLimiteCliente.setText(String.valueOf(cupon.getLimitePorCliente()));
        txtMontoMinimo.setText(String.valueOf(cupon.getMontoMinimo()));
        txtFechaInicio.setText(cupon.getFechaInicio());
        txtFechaFin.setText(cupon.getFechaFin());
        chkActivo.setSelected(cupon.isActivo());

        btnGuardar.setEnabled(false);
        btnModificar.setEnabled(true);
        btnDesactivar.setEnabled(true);
    }
    
    private void configurarEventos() {
        tblCupones.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                cargarCuponSeleccionado();
            }
        });
    }
    
    private Cupon obtenerCuponFormulario() {
        Cupon cupon = new Cupon();

        if (!txtIdCupon.getText().trim().isEmpty()) {
            cupon.setIdCupon(Integer.parseInt(txtIdCupon.getText().trim()));
        }

        cupon.setIdPromocion(Integer.parseInt(txtIdPromocion.getText().trim()));
        cupon.setCodigo(txtCodigo.getText().trim());
        cupon.setLimiteGlobal(Integer.parseInt(txtLimiteGlobal.getText().trim()));
        cupon.setLimitePorCliente(Integer.parseInt(txtLimiteCliente.getText().trim()));
        cupon.setUsosActuales(0);
        cupon.setMontoMinimo(Double.parseDouble(txtMontoMinimo.getText().trim()));
        cupon.setFechaInicio(txtFechaInicio.getText().trim());
        cupon.setFechaFin(txtFechaFin.getText().trim());
        cupon.setActivo(chkActivo.isSelected());

        return cupon;
    }
    
    private boolean validarFormulario() {
        if (txtIdPromocion.getText().trim().isEmpty() || txtCodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete la promoción y el código.");
            return false;
        }

        if (txtLimiteGlobal.getText().trim().isEmpty() || txtLimiteCliente.getText().trim().isEmpty() || txtMontoMinimo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete los límites y monto mínimo.");
            return false;
        }

        try {
            int limiteGlobal = Integer.parseInt(txtLimiteGlobal.getText().trim());
            int limiteCliente = Integer.parseInt(txtLimiteCliente.getText().trim());
            double montoMinimo = Double.parseDouble(txtMontoMinimo.getText().trim());

            if (limiteGlobal < 0 || limiteCliente < 0 || montoMinimo < 0) {
                JOptionPane.showMessageDialog(this, "Los valores no pueden ser negativos.");
                return false;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Revise los valores numéricos.");
            return false;
        }

        try {
            Timestamp inicio = Timestamp.valueOf(txtFechaInicio.getText().trim());
            Timestamp fin = Timestamp.valueOf(txtFechaFin.getText().trim());

            if (fin.before(inicio)) {
                JOptionPane.showMessageDialog(this, "La fecha final debe ser posterior a la inicial.");
                return false;
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Formato de fecha: AAAA-MM-DD HH:MM:SS");
            return false;
        }

        int idCupon = 0;

        if (!txtIdCupon.getText().trim().isEmpty()) {
            idCupon = Integer.parseInt(txtIdCupon.getText().trim());
        }

        if (cuponDAO.existeCodigo(txtCodigo.getText().trim(), idCupon)) {
            JOptionPane.showMessageDialog(this, "El código del cupón ya existe.");
            return false;
        }

        return true;
    }
    
