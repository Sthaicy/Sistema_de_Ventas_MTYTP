    private void configurarTipoPromocion() {
        String tipo = cmbTipo.getSelectedItem().toString();
        boolean usaValor = tipo.equals("PORCENTAJE") || tipo.equals("DESCUENTO_FIJO");
        boolean esCombo = tipo.equals("COMBO");

        if (tipo.equals("PORCENTAJE")) {
            jLabel8.setText("Porcentaje de descuento (%):");
        } else if (tipo.equals("DESCUENTO_FIJO")) {
            jLabel8.setText("Descuento fijo (Bs):");
        } else {
            jLabel8.setText("Valor del descuento:");
        }

        jLabel9.setText("Monto mínimo (Bs):");

        txtValor.setEnabled(usaValor);
        txtMontoMinimo.setEnabled(usaValor);
        txtPrecioCombo.setEnabled(esCombo);
        lblPrecioCombo.setEnabled(esCombo);
        txtCantidadRequerida.setEnabled(esCombo);
        lblCantidadRequerida.setEnabled(esCombo);

        if (!usaValor) {
            txtValor.setText("0");
            txtMontoMinimo.setText("0");
        }

        if (!esCombo) {
            txtPrecioCombo.setText("0");
            txtCantidadRequerida.setText("1");
        }
    }

    private void configurarEventos() {
        tblPromociones.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tblPromociones.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && tblPromociones.getSelectedRow() != -1) {
                cargarPromocionSeleccionada();
            }
        });
    }

    private void cargarPromociones() {
        modeloPromociones.setRowCount(0);

        ArrayList<Promocion> lista = promocionDAO.listar();

        for (Promocion promocion : lista) {
            Object[] fila = {
                promocion.getIdPromocion(),
                promocion.getNombre(),
                promocion.getTipo(),
                promocion.getValor(),
                promocion.getMontoMinimo(),
                promocion.getModoAplicacion(),
                promocion.getAlcance(),
                promocion.getAplicadoSobre(),
                promocion.isActivo() ? "Sí" : "No"
            };

            modeloPromociones.addRow(fila);
        }
    }

    private void cargarPromocionSeleccionada() {
        int fila = tblPromociones.getSelectedRow();
        if (fila == -1) return;

        fila = tblPromociones.convertRowIndexToModel(fila);
        int idPromocion = Integer.parseInt(tblPromociones.getModel().getValueAt(fila, 0).toString());

        Promocion promocion = promocionDAO.buscarPorId(idPromocion);
        if (promocion == null) {
            JOptionPane.showMessageDialog(this, "No se encontró la promoción.");
            return;
        }

        txtIdPromocion.setText(String.valueOf(promocion.getIdPromocion()));
        txtNombre.setText(promocion.getNombre());
        txtDescripcion.setText(promocion.getDescripcion());
        cmbTipo.setSelectedItem(promocion.getTipo());
        txtValor.setText(String.valueOf(promocion.getValor()));
        txtMontoMinimo.setText(String.valueOf(promocion.getMontoMinimo()));
        txtFechaInicio.setText(promocion.getFechaInicio());
        txtFechaFin.setText(promocion.getFechaFin());
        seleccionarLive(promocion.getIdLive());
        txtPrioridad.setText(String.valueOf(promocion.getPrioridad()));
        chkActivo.setSelected(promocion.isActivo());

        configurarTipoPromocion();
        btnGuardar.setEnabled(false);
        btnModificar.setEnabled(true);
        btnEliminar.setEnabled(true);
    }
    
