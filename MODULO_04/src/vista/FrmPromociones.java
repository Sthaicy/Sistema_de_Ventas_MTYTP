    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (txtIdPromocion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione una promoción.");
            return;
        }

        if (!validarFormulario()) {
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea guardar los cambios?",
            "Confirmar modificación",
            JOptionPane.YES_NO_OPTION
        );

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            Promocion promocion = obtenerPromocionFormulario();

            if (!promocionDAO.actualizar(promocion)) {
                JOptionPane.showMessageDialog(this, "No se pudo modificar la promoción.");
                return;
            }

            promocionDAO.eliminarRelaciones(promocion.getIdPromocion());

            boolean guardado = guardarAplicacionPromocion(
                promocion.getIdPromocion()
            );

            if (guardado) {
                JOptionPane.showMessageDialog(this, "Promoción modificada correctamente.");
            } else {
                JOptionPane.showMessageDialog(this,
                    "La promoción se modificó, pero hubo un problema al guardar sus relaciones.");
            }

            cargarPromociones();
            limpiarFormulario();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al modificar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (txtIdPromocion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione una promoción de la tabla.");
            return;
        }

        int idPromocion = Integer.parseInt(txtIdPromocion.getText().trim());
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Desea desactivar esta promoción?", "Confirmar desactivación", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        boolean desactivado = promocionDAO.desactivar(idPromocion);
        if (desactivado) {
            JOptionPane.showMessageDialog(this, "Promoción desactivada correctamente.");
            cargarPromociones();
            limpiarFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo desactivar la promoción.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

