    private void cargarAplicacionPromocion(int idPromocion, String alcance) {
        modeloElementos.setRowCount(0);

        if (alcance.equals("PRODUCTO")) {
            ArrayList<Object[]> productos =
                    promocionDAO.obtenerProductosPromocion(idPromocion);

            for (Object[] producto : productos) {
                modeloElementos.addRow(producto);
            }

        } else if (alcance.equals("CATEGORIA")) {
            ArrayList<Object[]> categorias =
                    promocionDAO.obtenerCategoriasPromocion(idPromocion);

            for (Object[] categoria : categorias) {
                modeloElementos.addRow(categoria);
            }
        }
    }
    
    

    private Promocion obtenerPromocionFormulario() {
        Promocion promocion = new Promocion();

        if (!txtIdPromocion.getText().trim().isEmpty()) {
            promocion.setIdPromocion(
                Integer.parseInt(txtIdPromocion.getText().trim())
            );
        }

        promocion.setNombre(txtNombre.getText().trim());
        promocion.setDescripcion(txtDescripcion.getText().trim());
        promocion.setTipo(cmbTipo.getSelectedItem().toString());

        promocion.setValor(Double.parseDouble(txtValor.getText().trim()));

        double montoMinimo = 0;

        if (!txtMontoMinimo.getText().trim().isEmpty()) {
            montoMinimo = Double.parseDouble(txtMontoMinimo.getText().trim());
        }

        promocion.setMontoMinimo(montoMinimo);
        promocion.setFechaInicio(txtFechaInicio.getText().trim());
        promocion.setFechaFin(txtFechaFin.getText().trim());

        promocion.setIdLive(obtenerIdLiveSeleccionado());

        promocion.setPrioridad(Integer.parseInt(txtPrioridad.getText().trim()));
        promocion.setActivo(chkActivo.isSelected());

        promocion.setModoAplicacion(cmbModoAplicacion.getSelectedItem().toString());
        promocion.setAlcance(cmbAplicarA.getSelectedItem().toString());

        double precioCombo = 0;

        if (!txtPrecioCombo.getText().trim().isEmpty()) {
            precioCombo = Double.parseDouble(txtPrecioCombo.getText().trim());
        }

        promocion.setPrecioCombo(precioCombo);

        return promocion;
    }
    
    private boolean validarFormulario() {
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el nombre de la promoción.");
            return false;
        }

        String tipo = cmbTipo.getSelectedItem().toString();

        if (tipo.equals("PORCENTAJE") || tipo.equals("DESCUENTO_FIJO")) {
            try {
                double valor = Double.parseDouble(txtValor.getText().trim());

                if (valor <= 0) {
                    JOptionPane.showMessageDialog(this, "El valor debe ser mayor a cero.");
                    return false;
                }

                if (tipo.equals("PORCENTAJE") && valor > 100) {
                    JOptionPane.showMessageDialog(this, "El porcentaje no puede superar 100.");
                    return false;
                }

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Ingrese un valor numérico válido.");
                return false;
            }
        }

        if (txtMontoMinimo.isEnabled() && !txtMontoMinimo.getText().trim().isEmpty()) {
            try {
                double monto = Double.parseDouble(txtMontoMinimo.getText().trim());

                if (monto < 0) {
                    JOptionPane.showMessageDialog(this, "El monto mínimo no puede ser negativo.");
                    return false;
                }

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "El monto mínimo debe ser numérico.");
                return false;
            }
        }

        if (tipo.equals("COMBO")) {
            try {
                double precio = Double.parseDouble(txtPrecioCombo.getText().trim());

                if (precio <= 0) {
                    JOptionPane.showMessageDialog(this, "El precio del combo debe ser mayor a cero.");
                    return false;
                }

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Ingrese un precio de combo válido.");
                return false;
            }
        }

        try {
            Timestamp inicio = Timestamp.valueOf(txtFechaInicio.getText().trim());
            Timestamp fin = Timestamp.valueOf(txtFechaFin.getText().trim());

            if (fin.before(inicio)) {
                JOptionPane.showMessageDialog(this, "La fecha fin debe ser posterior a la fecha inicio.");
                return false;
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Las fechas deben tener el formato:\nAAAA-MM-DD HH:MM:SS");
            return false;
        }

        try {
            int prioridad = Integer.parseInt(txtPrioridad.getText().trim());

            if (prioridad < 0) {
                JOptionPane.showMessageDialog(this, "La prioridad no puede ser negativa.");
                return false;
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La prioridad debe ser un número entero.");
            return false;
        }

        Integer idLive = obtenerIdLiveSeleccionado();
        if (idLive != null && !promocionDAO.existeLive(idLive)) {
            JOptionPane.showMessageDialog(this, "El Live seleccionado ya no existe.");
            cargarLives();
            return false;
        }

        return validarAplicacion();
    }

    private boolean validarAplicacion() {
        String alcance = cmbAplicarA.getSelectedItem().toString();

        if (alcance.equals("COMPRA")) {
            return true;
        }

        if (modeloElementos.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Agregue al menos un producto o categoría.");
            return false;
        }

        if (cmbTipo.getSelectedItem().toString().equals("COMBO")
                && !alcance.equals("PRODUCTO")) {
            JOptionPane.showMessageDialog(this, "Un combo debe estar formado por productos.");
            return false;
        }

        return true;
    }

    private boolean guardarAplicacionPromocion(int idPromocion) {
        String alcance = cmbAplicarA.getSelectedItem().toString();

        if (alcance.equals("COMPRA")) {
            return true;
        }

        for (int i = 0; i < modeloElementos.getRowCount(); i++) {
            int id = Integer.parseInt(
                modeloElementos.getValueAt(i, 0).toString()
            );

            if (alcance.equals("PRODUCTO")) {
                int cantidad = Integer.parseInt(
                    modeloElementos.getValueAt(i, 2).toString()
                );

                if (!promocionDAO.asociarProducto(idPromocion, id, cantidad)) {
                    return false;
                }

            } else {
                if (!promocionDAO.asociarCategoria(idPromocion, id)) {
                    return false;
                }
            }
        }

        return true;
    }

