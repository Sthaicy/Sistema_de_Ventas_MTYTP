    //NUEVO
    private void agregarElemento() {
        if (cmbElemento.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "No hay elementos disponibles.");
            return;
        }

        String seleccionado = cmbElemento.getSelectedItem().toString();
        String[] datos = seleccionado.split(" - ", 2);

        int id = Integer.parseInt(datos[0]);
        String nombre = datos[1];

        for (int i = 0; i < modeloElementos.getRowCount(); i++) {
            int idExistente = Integer.parseInt(
                modeloElementos.getValueAt(i, 0).toString()
            );

            if (idExistente == id) {
                JOptionPane.showMessageDialog(this, "El elemento ya fue agregado.");
                return;
            }
        }

        int cantidad = 1;

        if (cmbTipo.getSelectedItem().toString().equals("COMBO")) {
            try {
                cantidad = Integer.parseInt(txtCantidadRequerida.getText().trim());

                if (cantidad <= 0) {
                    JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a cero.");
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Ingrese una cantidad válida.");
                return;
            }
        }

        modeloElementos.addRow(new Object[]{id, nombre, cantidad});
    }
    
