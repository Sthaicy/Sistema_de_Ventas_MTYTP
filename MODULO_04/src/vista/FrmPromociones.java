    private void cargarElementosDisponibles() {
        cmbElemento.removeAllItems();

        String alcance = cmbAplicarA.getSelectedItem().toString();

        if (alcance.equals("PRODUCTO")) {
            ArrayList<String> productos = promocionDAO.listarProductosActivos();

            for (String producto : productos) {
                cmbElemento.addItem(producto);
            }
        } else if (alcance.equals("CATEGORIA")) {
            ArrayList<String> categorias = promocionDAO.listarCategoriasActivas();

            for (String categoria : categorias) {
                cmbElemento.addItem(categoria);
            }
        }
    }
    
