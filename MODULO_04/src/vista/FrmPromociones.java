    private void cargarLives() {
        cmbLive.removeAllItems();
        cmbLive.addItem("Sin Live");

        ArrayList<String> lives = promocionDAO.listarLives();
        for (String live : lives) {
            cmbLive.addItem(live);
        }
    }

    private Integer obtenerIdLiveSeleccionado() {
        if (cmbLive.getSelectedIndex() <= 0) {
            return null;
        }

        String live = cmbLive.getSelectedItem().toString();
        String[] datos = live.split(" - ", 2);
        return Integer.parseInt(datos[0]);
    }

    private void seleccionarLive(Integer idLive) {
        cmbLive.setSelectedIndex(0);
        if (idLive == null) {
            return;
        }

        for (int i = 1; i < cmbLive.getItemCount(); i++) {
            if (cmbLive.getItemAt(i).startsWith(idLive + " - ")) {
                cmbLive.setSelectedIndex(i);
                return;
            }
        }
    }

