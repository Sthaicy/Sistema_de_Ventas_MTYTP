    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        if (!validarFormulario()) {
            return;
        }

        try {
            Promocion promocion = obtenerPromocionFormulario();

            int idPromocion = promocionDAO.insertar(promocion);

            if (idPromocion == -1) {
                JOptionPane.showMessageDialog(this, "No se pudo registrar la promoción.");
                return;
            }

            boolean guardado = guardarAplicacionPromocion(idPromocion);

            if (guardado) {
                JOptionPane.showMessageDialog(this, "Promoción registrada correctamente.");
            } else {
                JOptionPane.showMessageDialog(this,
                    "La promoción se registró, pero hubo un problema al guardar sus relaciones.");
            }

            cargarPromociones();
            limpiarFormulario();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

